FÓRMULA
Fahrenheit = (Celsius × 1.8) + 32

Observe que a conversão possui duas operações. A multiplicação deve acontecer
antes da soma. Os parênteses tornam essa intenção mais fácil de entender.

COMO PENSAR NA RESOLUÇÃO
1. Armazene a temperatura em Celsius em uma variável.
2. Traduza a fórmula para uma expressão aritmética em PHP.
3. Guarde o resultado em uma variável diferente.
4. Mostre a temperatura inicial e a convertida na mesma mensagem.

EXEMPLOS ESPERADOS
- 0 °C -> 32 °F
- 25 °C -> 77 °F
- 100 °C -> 212 °F
- -40 °C -> -40 °F

REQUISITOS
- O programa deve funcionar com temperaturas negativas e decimais.
- Use nomes de variáveis que deixem evidente a escala de cada valor.
- O valor em Fahrenheit precisa ser calculado, não informado manualmente.

TESTE DE CONFIANÇA
O valor -40 é especialmente útil: Celsius e Fahrenheit apresentam o mesmo
número nesse ponto. Se o resultado for diferente, revise a fórmula.

DESAFIO OPCIONAL
Faça também o caminho inverso. Pesquise ou deduza como converter Fahrenheit
para Celsius sem apagar a primeira conversão.
