COMO PENSAR
1. Crie um acumulador iniciado com o valor neutro da soma.
2. Leia um número.
3. Enquanto ele for diferente de zero, some-o ao total e leia o próximo.
4. Depois que o loop terminar, mostre o acumulador.

TESTE COM ESTA SEQUÊNCIA
5, 3, -2, 0 -> soma esperada: 6.

PERGUNTA IMPORTANTE
O zero deve ser somado? Ele mudaria o resultado? Mesmo que não mude, entenda
por que ele serve para controlar o loop e não como um dado da sequência.
